/// ⚑ **THE SHAPE, MEASURED OFF THE PARSED DESCRIPTORS.** The final artifact is the segment plus
/// exactly 64 constraints, at the same width and the same PI count — the discharge APPENDS.
#[test]
fn the_lean_artifacts_declare_the_layout_this_file_reads() {
    let seg = descriptor(SEG_JSON);
    let fin = descriptor(FINAL_JSON);

    assert_eq!(seg.name, "dregg-mina-accumulator-seg::v1");
    assert_eq!(fin.name, "dregg-mina-accumulator-final::v1");
    assert_ne!(seg.name, fin.name, "a name is a KEY, not a label");

    for d in [&seg, &fin] {
        assert_eq!(d.trace_width, WIDTH, "3 048 at EVERY chain depth");
        assert_eq!(
            d.public_input_count, PI_COUNT,
            "two projective Vesta points: the claim and the result"
        );
        assert_eq!(
            d.tables.len(),
            4,
            "main + range_w8 + range_w16 + range_w1 — the sound row's union, nothing new"
        );
    }
    assert_eq!(seg.constraints.len(), SEG_CONSTRAINTS);
    assert_eq!(fin.constraints.len(), FINAL_CONSTRAINTS);

    // ⚑ TWO INDEPENDENT ARTIFACTS ON DISK, and the segment's constraints are a genuine PREFIX of
    // the final's. This is what makes the discharge-gate indices below derived rather than guessed:
    // everything the segment forces, the final artifact forces identically.
    assert_eq!(
        seg.constraints,
        fin.constraints[..SEG_CONSTRAINTS],
        "the final descriptor must EXTEND the segment, not re-author it"
    );
}

/// ⚑ **THE SELECTOR CENSUS, AND IT IS WHERE A RE-SCOPE BECOMES VISIBLE.**
///
/// 96 `.transition` threads in both artifacts; 64 `when_last_row` discharge boundaries in the final
/// one and NONE in the segment. Both families are byte-identical algebra under a different
/// selector, so neither move shows up in a constraint COUNT:
///
/// * `.transition → .all` on a thread accepts strictly more (on the last row p3's `next` is the
///   WRAP row);
/// * `.last → .all` on the discharge would demand that EVERY intermediate accumulator vanish — a
///   descriptor that accepts nothing, which reads as "very strict" and is worthless.
///
/// The discharge bodies are also checked to be exactly the `OUT_X` and `OUT_Z` limb columns, so a
/// gate pointed at the wrong block (say `OUT_Y`, which for the point at infinity is NONZERO) is not
/// something this census would pass.
#[test]
fn the_discharge_is_sixty_four_last_row_gates_and_the_threads_are_transition() {
    use dregg_circuit::lean_descriptor_air::{LeanExpr, VmConstraint, VmRow};

    let seg = descriptor(SEG_JSON);
    let fin = descriptor(FINAL_JSON);

    for (who, d, want_last) in [("seg", &seg, 0usize), ("final", &fin, 64usize)] {
        let mut transition = 0usize;
        let mut every_row = 0usize;
        let mut last_boundaries: Vec<usize> = Vec::new();
        for c in &d.constraints {
            match c {
                VmConstraint2::WindowGate(g) if g.on_transition => transition += 1,
                VmConstraint2::WindowGate(_) => every_row += 1,
                VmConstraint2::Base(VmConstraint::Boundary {
                    row: VmRow::Last,
                    body,
                }) => match body {
                    LeanExpr::Var(v) => last_boundaries.push(*v),
                    other => panic!("{who}: a last-row boundary with an unexpected body {other:?}"),
                },
                _ => {}
            }
        }
        assert_eq!(
            transition, 96,
            "{who}: three coordinates x 32 limbs of thread"
        );
        assert_eq!(
            every_row, 0,
            "{who}: an `.all`-scoped window accepts strictly more than a transition one"
        );
        assert_eq!(
            last_boundaries.len(),
            want_last,
            "{who}: the discharge gates"
        );

        if want_last > 0 {
            last_boundaries.sort_unstable();
            let mut want: Vec<usize> = (0..SK).flat_map(|i| [OUT[0] + i, OUT[2] + i]).collect();
            want.sort_unstable();
            assert_eq!(
                last_boundaries, want,
                "{who}: the discharge must vanish the terminal X and Z blocks — and NOT Y, which \
                 is nonzero at the point at infinity"
            );
        }
    }

    // …and the 192 endpoint pins, which are what a fold node reads.
    let pins = fin
        .constraints
        .iter()
        .filter(|c| matches!(c, VmConstraint2::Base(VmConstraint::PiBinding { .. })))
        .count();
    assert_eq!(
        pins, 192,
        "96 incoming limbs pinned first-row, 96 outgoing last"
    );
}

