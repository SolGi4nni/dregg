const SEG_JSON: &str = include_str!("../descriptors/by-name/mina-accumulator-seg.json");
const FINAL_JSON: &str = include_str!("../descriptors/by-name/mina-accumulator-final.json");

const DISCHARGING: &str = include_str!("fixtures/mina-accumulator-discharging-trace.txt");
const OPEN: &str = include_str!("fixtures/mina-accumulator-open-trace.txt");
const UNCHAINED: &str = include_str!("fixtures/mina-accumulator-unchained-trace.txt");

/// `PastaCurveSound.RCB_WIDTH`.
const WIDTH: usize = 3048;
/// Eight rows: seven generator adds and the closing one. A power of two, which the deployed prover
/// requires of a base trace.
const ROWS: usize = 8;
/// Limbs per Pasta field element in the sound encoding (`PastaFieldSound.SK`).
const SK: usize = 32;

/// The accumulator's three INPUT blocks, contiguous at `0, 32, 64` (`MinaAccumulatorAir.ACC_*`).
const ACC: [usize; 3] = [0, SK, 2 * SK];
/// The accumulator's three OUTPUT blocks — the gadget's SSA `v 26 / v 29 / v 32`, which are NOT
/// contiguous. That is exactly why the published PI side is.
const OUT: [usize; 3] = [1024, 1120, 1216];

/// `4 476` sound row-local + `96` threads + `192` endpoint pins.
const SEG_CONSTRAINTS: usize = 4476 + 96 + 192;
/// …and the `64` discharge gates on top.
const FINAL_CONSTRAINTS: usize = SEG_CONSTRAINTS + 64;
/// `6 · SK` — two projective Vesta points.
const PI_COUNT: usize = 6 * SK;

fn descriptor(json: &str) -> EffectVmDescriptor2 {
    parse_vm_descriptor2(json).expect("the STRICT deployed checker parses the accumulator AIR")
}

fn trace(text: &str) -> Vec<Vec<BabyBear>> {
    let rows = cells(text);
    assert_eq!(rows.len(), ROWS);
    assert!(rows.iter().all(|r| r.len() == WIDTH));
    rows.into_iter()
        .map(|r| {
            r.into_iter()
                .map(|c| BabyBear::new(u32::try_from(c).expect("a cell fits a u32")))
                .collect()
        })
        .collect()
}

/// The raw decimal cells, for assertions about the FIXTURE rather than about the field.
fn cells(text: &str) -> Vec<Vec<u64>> {
    text.lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| {
            l.split_whitespace()
                .map(|t| t.parse::<u64>().expect("cell is a u64 decimal"))
                .collect()
        })
        .collect()
}

/// ⚑ **THE PUBLISHED CLAIM AND RESULT, READ OFF THE TRACE'S OWN PINNED COLUMNS.**
///
/// `PI[0..95]` are the FIRST row's `ACC_X‖ACC_Y‖ACC_Z` limbs — the accumulator the chain starts
/// from, which in the accumulator check is the claim commitment `C`. `PI[96..191]` are the LAST
/// row's `OUT_X‖OUT_Y‖OUT_Z` limbs. Derived from the columns the Lean pins name, never authored.
fn public_inputs(t: &[Vec<BabyBear>]) -> Vec<BabyBear> {
    let mut pis = Vec::with_capacity(PI_COUNT);
    for base in ACC {
        for i in 0..SK {
            pis.push(t[0][base + i]);
        }
    }
    for base in OUT {
        for i in 0..SK {
            pis.push(t[ROWS - 1][base + i]);
        }
    }
    assert_eq!(pis.len(), PI_COUNT);
    pis
}

/// p3 numbers AIR constraints skipping `Lookup`s, so a descriptor constraint-LIST index is not a p3
/// index. ⚑ DERIVED from the parsed artifact, never a literal: a widening that inserts a gate moves
/// both sides only if the mapping is real.
fn air_index(desc: &EffectVmDescriptor2, list_index: usize) -> usize {
    assert!(
        list_index < desc.constraints.len(),
        "constraint {list_index} is past the end of {}'s {} constraints",
        desc.name,
        desc.constraints.len()
    );
    assert!(
        !matches!(desc.constraints[list_index], VmConstraint2::Lookup(_)),
        "constraint {list_index} is a LOOKUP; it has no AIR-constraint index"
    );
    desc.constraints[..list_index]
        .iter()
        .filter(|c| !matches!(c, VmConstraint2::Lookup(_)))
        .count()
}

/// ⚑ **THE REFUSAL NAMED THE GATE THIS TOOTH NAMES** — not merely "something objected".
///
/// [`assert_violated_constraint_not_bus`] holds in EVERY profile and is the load-bearing negative
/// clause: a tooth aimed at the discharge gate must not be kept green by a range lookup's LogUp
/// failing instead. The ROW and the failed-constraint SET are only available when p3's debug check
/// is the mechanism; under `--release` the verdict is `OodEvaluationMismatch`, which carries
/// neither — said out loud rather than left as a silent weakening.
#[track_caller]
fn refused_by_gates(
    what: &str,
    refusal: &Refusal<String>,
    desc: &EffectVmDescriptor2,
    gates: &[usize],
    row: usize,
) -> String {
    let reason = refusal.reason();
    assert_violated_constraint_not_bus(what, &reason);

    let Some(rest) = reason.split("constraints not satisfied on row ").nth(1) else {
        return reason;
    };
    let (got_row, rest) = rest
        .split_once(':')
        .expect("p3 renders `on row N: failed constraints = [...]`");
    assert_eq!(
        got_row.trim().parse::<usize>().expect("a row index"),
        row,
        "{what}: refused on the wrong ROW — the gate this tooth names fires on row {row}: {reason}"
    );
    let list = rest
        .split_once('[')
        .and_then(|(_, r)| r.split_once(']'))
        .expect("p3 renders the failed set in brackets")
        .0;
    let got: Vec<usize> = list
        .split(',')
        .map(|t| {
            t.trim()
                .trim_start_matches('#')
                .parse::<usize>()
                .expect("a constraint index")
        })
        .collect();
    assert!(!got.is_empty(), "{what}: p3 named no failed constraint");
    let want: Vec<usize> = gates.iter().map(|&i| air_index(desc, i)).collect();
    for g in &got {
        assert!(
            want.contains(g),
            "{what}: constraint #{g} objected and it is NOT one of the gates this tooth names \
             ({want:?}). Something other than the named gate is what catches this forgery: {reason}"
        );
    }
    reason
}

