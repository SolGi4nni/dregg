//! # ⚑ THE DEFERRED IPA ACCUMULATOR CHECK, PROVED AND REFUSED IN A CIRCUIT.
//!
//! ## Substrate, said out loud (HOUSE LAW #1)
//!
//! **The AIR is Lean-authored.** `dregg-mina-accumulator-seg::v1` and
//! `dregg-mina-accumulator-final::v1` are `EffectLower.lowerAir` of
//! `Dregg2.Circuit.Emit.MinaAccumulatorAir.{accSegAir, accFinalAir}` — the threaded sound VESTA RCB
//! row with its two endpoints published, and (in `-final`) the 64 `.last`-row window gates that
//! force the terminal accumulator to be the point at infinity. Nothing in this file authors a
//! constraint, a `Builder` gadget or an `air_accepts` predicate. It parses the Lean artifacts,
//! reads Lean-generated trace fixtures, and runs the deployed prover. **When the prover refuses a
//! trace, the WITNESS is wrong.**
//!
//! ## What is being checked, and against what it was NOT checked before
//!
//! `mina-rust`'s verifier `&&`s `Ipa::Step::accumulator_check` into `batch_step_dlog_check`
//! (`verify.ml:135-146`). dregg discharges it **natively** in
//! `bridge/src/mina_accumulator_discharge.rs` — whose own header says *"Nothing here is an AIR"* —
//! and a Mina head's acceptance depends on that native oracle
//! (`turn/src/executor/mina_accumulator_oracle.rs`). This file is the first time the relation is
//! inside a constraint system.
//!
//! Read as a running sum, the batched discharge `Σᵢrⁱ·Cᵢ − ⟨Σᵢrⁱ·s(u⃗ᵢ), G⟩ == O` is a chain of
//! complete additions that starts at the claim commitment and must end at the identity:
//!
//! ```text
//!     acc_0 = C  ;  acc_{r+1} = acc_r + A_r  ;  acc_n = O
//! ```
//!
//! so the entry accumulator IS the claim (published at `PI[0..95]`, elementwise at full width, no
//! digest) and `acc_n = O` IS the check.
//!
//! ## ⚑ THE THREE FIXTURES AND WHICH GATE SEPARATES WHICH PAIR
//!
//! All three are Lean-generated by `metatheory/EmitMinaAccumulator.lean` from the same
//! `PastaCurveSound.rcbSoundRow` chained by `PastaCurveComplete.rcbAddM`, on **Vesta**.
//!
//! | fixture       | threads hold | terminal `X`/`Z` | `-seg` | `-final` |
//! |---------------|--------------|------------------|--------|----------|
//! | `discharging` | yes          | all zero         | proves | proves   |
//! | `open`        | yes          | all 64 NONZERO   | proves | REFUSED  |
//! | `unchained`   | **no** (6→7) | all zero         | REFUSED| REFUSED  |
//!
//! * `discharging` vs `open` isolates the **discharge gate**: both are eight independently honest
//!   rows with every thread held; the only difference is whether the accumulator vanished.
//! * `discharging` vs `unchained` isolates the **thread**: eight independently honest rows whose
//!   accumulator does not chain, which is exactly what a ladder looks like when the accumulator is
//!   re-pinned instead of threaded.
//!
//! ## ⚑ THE FALSIFIERS ARE CHECKED TO MOVE, AND TO MOVE SOMETHING NONZERO
//!
//! This campaign shipped two falsifiers that passed for the wrong reason — one moved a zero into a
//! zero, one was refused by a range lookup rather than by the gate under test. So before any
//! polarity runs:
//!
//! * `the_falsifiers_move_and_what_they_move_is_nonzero` asserts the cell counts AND that the
//!   `open` fixture's terminal `X`/`Z` limbs are nonzero in all 64 positions — the discharge gate
//!   is refusing a genuinely non-vanishing accumulator, not an absent one;
//! * `every_fixture_cell_is_inside_the_declared_limb_width` asserts every input-block cell is
//!   `< 2^8` and every cell is `< 2^16`, so no range lookup can be the refusal; and
//! * every refusal tooth calls [`assert_violated_constraint_not_bus`], which holds in EVERY profile
//!   — so a LogUp imbalance cannot stand in for the gate under test.
//!
//! ⚠ **RUN IN RELEASE.** These descriptors carry lookups, so an algebraic refusal is a p3
//! `#[cfg(debug_assertions)]` PANIC in debug and a clean `Err` in release:
//!
//! ```text
//! cargo test -p dregg-circuit --release --test mina_accumulator_air_proves -- --nocapture
//! ```
//!
//! ## ⚠ WHAT THIS DOES NOT ESTABLISH
//!
//! **Not that the addends are the SRS.** `MinaAccumulatorAir.accumulator_discharge_forced` forces
//! the chain of the trace's own addends to vanish and says nothing about what those addends are;
//! forcing `A_r` to be the `r`-th scaled generator is the ROUTING half, it lives in
//! `PastaMsmBucketed`'s exact-public lookups, and `the_routing_tuple_does_not_fit_one_table` prices
//! the one deployed constant in its way. So this is the **SUMMATION** half of the accumulator
//! check, in a circuit, soundly, at full 256-bit width — not the whole check.

use dregg_circuit::BabyBear;
use dregg_circuit::descriptor_ir2::{
    EffectVmDescriptor2, MemBoundaryWitness, VmConstraint2, parse_vm_descriptor2,
    prove_vm_descriptor2, verify_vm_descriptor2,
};
use dregg_circuit::refusal::{
    Refusal, assert_violated_constraint_not_bus, must_refuse_or_unsat_panic,
};

