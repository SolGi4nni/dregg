/// ⚑ **POLARITY 1 — THE ACCUMULATOR CHECK PROVES.**
///
/// A real threaded chain of eight sound Vesta complete additions that ends at the point at
/// infinity, proved and verified by the deployed `prove_vm_descriptor2` / `verify_vm_descriptor2`
/// against the descriptor whose `.last` gates DEMAND that it vanish. The public inputs are the
/// chain's own published endpoints: the claim at `PI[0..95]` and the result at `PI[96..191]`.
#[test]
fn the_discharging_chain_proves_under_both_descriptors() {
    let t = trace(DISCHARGING);
    let pis = public_inputs(&t);
    for (who, json) in [("seg", SEG_JSON), ("final", FINAL_JSON)] {
        let d = descriptor(json);
        let proof = prove_vm_descriptor2(&d, &t, &pis, &MemBoundaryWitness::default(), &[])
            .unwrap_or_else(|e| panic!("{who}: the discharging chain must prove: {e:?}"));
        verify_vm_descriptor2(&d, &proof, &pis)
            .unwrap_or_else(|e| panic!("{who}: the discharging proof must verify: {e:?}"));
    }
}

/// ⚑⚑ **POLARITY 2 — AN OPEN ACCUMULATOR IS REFUSED, AND THE DISCHARGE GATE IS WHAT REFUSES IT.**
///
/// This is the OLD-ADMITS / NEW-REJECTS pair, and it cannot rot into agreement: the same eight
/// honest rows, every thread held, every cell a legal limb, PROVE under `dregg-mina-accumulator-
/// seg::v1` and are REFUSED under `dregg-mina-accumulator-final::v1`. The refusing constraints are
/// the 64 `.last` window gates at descriptor constraint indices `SEG_CONSTRAINTS .. FINAL_CONSTRAINTS`
/// — derived from the parsed prefix relation, not pinned as a literal — firing on the LAST row.
///
/// Deleting the discharge turns the second half green while the first half stays green, which is
/// what makes the first half the negative control rather than decoration.
#[test]
fn an_open_accumulator_is_refused_by_the_discharge_gate() {
    let t = trace(OPEN);
    let pis = public_inputs(&t);

    // OLD ADMITS: the segment descriptor has nothing to say about vanishing, and says nothing.
    let seg = descriptor(SEG_JSON);
    let proof = prove_vm_descriptor2(&seg, &t, &pis, &MemBoundaryWitness::default(), &[]).expect(
        "the OPEN chain is eight honest threaded rows — the SEGMENT descriptor must accept it, or \
         the refusal below would be about something other than the discharge",
    );
    verify_vm_descriptor2(&seg, &proof, &pis).expect("and the segment proof verifies");

    // NEW REJECTS.
    let fin = descriptor(FINAL_JSON);
    let gates: Vec<usize> = (SEG_CONSTRAINTS..FINAL_CONSTRAINTS).collect();
    let refusal = must_refuse_or_unsat_panic("an open accumulator under -final", || {
        prove_vm_descriptor2(&fin, &t, &pis, &MemBoundaryWitness::default(), &[])
    });
    let reason = refused_by_gates(
        "an open accumulator under -final",
        &refusal,
        &fin,
        &gates,
        ROWS - 1,
    );
    println!("discharge gate refused the open chain: {reason}");
}

/// ⚑ **POLARITY 3 — AND THE THREAD IS WHAT REFUSES THE UNCHAINED ONE.**
///
/// Eight independently honest rows whose accumulator does not chain — the shape a ladder takes when
/// the accumulator is re-pinned instead of threaded. It is refused by the SEGMENT descriptor, so
/// the refusal is the thread's and not the discharge's: the unchained fixture's terminal
/// accumulator vanishes exactly like the honest one's.
#[test]
fn the_unchained_chain_is_refused_by_the_thread() {
    let t = trace(UNCHAINED);
    let pis = public_inputs(&t);
    let seg = descriptor(SEG_JSON);
    let refusal = must_refuse_or_unsat_panic("an unchained accumulator under -seg", || {
        prove_vm_descriptor2(&seg, &t, &pis, &MemBoundaryWitness::default(), &[])
    });
    assert_violated_constraint_not_bus("an unchained accumulator under -seg", &refusal.reason());
    println!("thread refused the unchained chain: {}", refusal.reason());
}

/// ⚑ **AND THE PUBLISHED ENDPOINTS ARE PINNED, NOT DECORATIVE.**
///
/// A prover that publishes a claim the trace did not start from — one limb of `PI[0..95]` displaced
/// by one — is refused. Without this the 192 pins would be a decoration and a fold node connecting
/// them would be connecting free prover scalars, which is precisely the "re-pins the same public
/// inputs" failure the phase-2 chain already paid for.
#[test]
fn a_displaced_claim_is_refused_by_the_endpoint_pins() {
    let t = trace(DISCHARGING);
    let honest = public_inputs(&t);
    let seg = descriptor(SEG_JSON);

    for slot in [0usize, 40, 95, 96, 150, 191] {
        let mut pis = honest.clone();
        pis[slot] = honest[slot] + BabyBear::new(1);
        assert_ne!(pis[slot], honest[slot], "the tamper must MOVE the value");
        let refusal = must_refuse_or_unsat_panic("a displaced endpoint publication", || {
            prove_vm_descriptor2(&seg, &t, &pis, &MemBoundaryWitness::default(), &[])
        });
        assert_violated_constraint_not_bus(
            &format!("a displaced endpoint publication at PI[{slot}]"),
            &refusal.reason(),
        );
    }
}
