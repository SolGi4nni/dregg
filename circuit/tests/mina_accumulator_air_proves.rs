/// Does the accumulator thread hold across every seam of this fixture? Returns the broken ones.
fn broken_seams(t: &[Vec<u64>]) -> Vec<usize> {
    (0..t.len() - 1)
        .filter(|&r| (0..3).any(|b| (0..SK).any(|i| t[r + 1][ACC[b] + i] != t[r][OUT[b] + i])))
        .collect()
}

/// ⚑ **THE HONEST TRACE THREADS, WALKS, AND VANISHES BY ARITHMETIC.**
///
/// The accumulator genuinely walks `2G, 3G, … 8G` and then meets `−8G`, so the terminal `X` and `Z`
/// blocks are the canonical all-zero limbs — `pasta_msm::is_identity` — while `Y` is NOT zero,
/// which is what makes it the projective point at infinity `(0 : y : 0)` rather than an all-zero
/// scribble. A fixed-point fixture would make every thread gate vacuous; eight distinct
/// accumulators is what rules that out.
#[test]
fn the_discharging_fixture_threads_walks_and_vanishes() {
    let t = cells(DISCHARGING);
    assert_eq!(t.len(), ROWS);
    assert_eq!(
        broken_seams(&t),
        Vec::<usize>::new(),
        "every seam must chain"
    );

    for i in 0..SK {
        assert_eq!(
            t[ROWS - 1][OUT[0] + i],
            0,
            "terminal X limb {i} must vanish"
        );
        assert_eq!(
            t[ROWS - 1][OUT[2] + i],
            0,
            "terminal Z limb {i} must vanish"
        );
    }
    assert!(
        (0..SK).any(|i| t[ROWS - 1][OUT[1] + i] != 0),
        "the identity is (0 : y : 0) with y NONZERO — an all-zero triple is not a projective point \
         and would make this exhibit a scribble rather than a discharge"
    );

    let accs: std::collections::HashSet<Vec<u64>> = (0..ROWS)
        .map(|r| t[r][ACC[0]..ACC[0] + SK].to_vec())
        .collect();
    assert_eq!(
        accs.len(),
        ROWS,
        "eight DISTINCT accumulators; a fixed point would make the threads vacuous"
    );
}

/// ⚑ **THE FALSIFIERS MOVE, AND WHAT THEY MOVE IS NONZERO.** The check this campaign paid for
/// twice: one tamper moved a zero into a zero, another was refused by a range lookup.
#[test]
fn the_falsifiers_move_and_what_they_move_is_nonzero() {
    let d = cells(DISCHARGING);
    let o = cells(OPEN);
    let u = cells(UNCHAINED);

    for (name, f) in [("open", &o), ("unchained", &u)] {
        assert_eq!(f.len(), ROWS);
        let moved: usize = (0..ROWS)
            .map(|r| (0..WIDTH).filter(|&c| d[r][c] != f[r][c]).count())
            .sum();
        assert!(
            moved > 2000,
            "{name}: the forgery must MOVE cells, not relabel them; moved = {moved}"
        );
        let differing: Vec<usize> = (0..ROWS).filter(|&r| d[r] != f[r]).collect();
        assert_eq!(
            differing,
            vec![ROWS - 1],
            "{name}: only the last row differs, so a refusal cannot be blamed on collateral damage"
        );
    }

    // ⚑ THE `open` FIXTURE'S TERMINAL ACCUMULATOR IS NONZERO IN ALL 64 DISCHARGED POSITIONS.
    // A tamper that left the terminal limbs at zero would be refused by nothing, and a tamper that
    // moved one limb would leave 63 gates satisfied — this asserts the gate is refusing a genuinely
    // non-vanishing accumulator.
    let nonzero = (0..SK).filter(|&i| o[ROWS - 1][OUT[0] + i] != 0).count()
        + (0..SK).filter(|&i| o[ROWS - 1][OUT[2] + i] != 0).count();
    assert_eq!(
        nonzero, 64,
        "the open chain's terminal X and Z limbs must ALL be nonzero: the discharge gate is being \
         shown a real point, not an absent one"
    );

    // …and every thread still holds in `open`, so the discharge gate is the ONLY thing left.
    assert_eq!(broken_seams(&o), Vec::<usize>::new());
    // …while `unchained` breaks exactly the 6 -> 7 seam and nothing else.
    assert_eq!(broken_seams(&u), vec![ROWS - 2]);
}

/// ⚑ **EVERY FIXTURE CELL IS INSIDE THE DECLARED LIMB WIDTH** — so a range lookup CANNOT be what
/// refuses any of them. This is the second wrong-reason failure this campaign hit.
#[test]
fn every_fixture_cell_is_inside_the_declared_limb_width() {
    for (name, text) in [
        ("discharging", DISCHARGING),
        ("open", OPEN),
        ("unchained", UNCHAINED),
    ] {
        let t = cells(text);
        for (r, row) in t.iter().enumerate() {
            for c in 0..6 * SK {
                assert!(
                    row[c] < 256,
                    "{name} row {r} input limb {c} = {} leaves the declared 8-bit width; a range \
                     lookup would refuse this trace and the gate under test would never be reached",
                    row[c]
                );
            }
            for (c, v) in row.iter().enumerate() {
                assert!(
                    *v < 65536,
                    "{name} row {r} cell {c} = {v} is outside the widest declared range table"
                );
            }
        }
    }
}

